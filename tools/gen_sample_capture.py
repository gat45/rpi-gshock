#!/usr/bin/env python3
"""Extract real, byte-exact sample frames from the DW-H5600 captures.

The generated header is used by BOTH the FAP (REVERSE > SAMPLE) and the host
unit tests, so the firmware and the tests decode the same measured bytes.

Usage:
    python tools/gen_sample_capture.py [--src DIR] [--out FILE]
"""
from __future__ import annotations

import argparse
import csv
import glob
import os
import sys

DEFAULT_SRC = os.path.join(
    os.path.dirname(__file__), "..", "..", "..",
    "gshock", "DW-H5600-EMU", "analysis", "btsnoop",
)

PAIR_BYTES = 5 + 15 + 5 + 99  # 0x00 record + 0x65 record


def crc16_kermit(data: bytes) -> int:
    crc = 0
    for b in data:
        crc ^= b
        for _ in range(8):
            crc = (crc >> 1) ^ 0x8408 if crc & 1 else crc >> 1
    return crc


def crc_ok(wire: bytes) -> bool:
    return len(wire) >= 4 and crc16_kermit(wire[1:-2]) == int.from_bytes(wire[-2:], "little")


def payload_len(wire: bytes) -> int:
    return len(wire) - 3 if crc_ok(wire) else len(wire) - 1


def record_header(wire: bytes):
    if not crc_ok(wire):
        return None, None
    body = bytes(b ^ 0xFF for b in wire[1:-2])
    if len(body) < 5:
        return None, None
    return body[0], int.from_bytes(body[1:5], "little")


def rows(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        yield from csv.DictReader(fh)


def collect(files):
    names = []
    conditions = []

    # Pass 1: names and conditions across every capture.
    for path in files:
        for r in rows(path):
            if r.get("opcode") != "0x1B":
                continue
            raw = (r.get("valeur") or "").strip()
            if not raw:
                continue
            if raw.startswith("23"):
                if raw not in names:
                    names.append(raw)
            elif raw.startswith("28") and len(raw) >= 10:
                key = raw[:6]  # command + raw level + temperature
                if key not in {c[:6] for c in conditions}:
                    conditions.append(raw)

    # Pass 2: the first contiguous run that covers a full 0x00 + 0x65 pair.
    flow = []
    for path in files:
        acc = 0
        collecting = False
        for r in rows(path):
            if r.get("opcode") != "0x1B":
                continue
            raw = (r.get("valeur") or "").strip()
            if not raw.startswith("05"):
                continue

            if collecting:
                wire = bytes.fromhex(raw)
                flow.append((raw, "continuation" if not crc_ok(wire) else "crc"))
                acc += payload_len(wire)
                if acc >= PAIR_BYTES:
                    return flow, names, conditions
                continue

            rtype, rlen = record_header(bytes.fromhex(raw))
            if (rtype, rlen) == (0x00, 15):
                collecting = True
                acc = payload_len(bytes.fromhex(raw))
                flow.append((raw, "type 0x00 len 15"))

    return flow, names, conditions


def array(name, hexstr, comment):
    data = bytes.fromhex(hexstr)
    vals = ", ".join(f"0x{b:02X}" for b in data)
    return [f"/* {comment} */", f"static const uint8_t {name}[] = {{{vals}}};"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=DEFAULT_SRC)
    ap.add_argument(
        "--out",
        default=os.path.join(os.path.dirname(__file__), "..", "protocol", "sample_data.h"),
    )
    args = ap.parse_args()

    files = sorted(glob.glob(os.path.join(args.src, "*_att.csv")))
    if not files:
        sys.exit(f"no captures in {args.src}")

    flow, names, conditions = collect(files)
    if not flow:
        sys.exit("no CRC-valid 0x00 record chunk found")

    names = names[:2]
    conditions = conditions[:3]

    out = [
        "/* GENERATED by tools/gen_sample_capture.py - do not edit.",
        " * Real wire bytes from the DW-H5600 btsnoop captures.",
        " * Shared by the FAP sample decoder and tests/native/test_decoders.c. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    const uint8_t* data;",
        "    uint16_t len;",
        "} CasioSampleFrame;",
        "",
    ]

    for i, (hexstr, label) in enumerate(flow):
        out.extend(array(f"kSampleFlowChunk{i}", hexstr, f"0x0013 {label}"))
        out.append("")

    out.append("static const CasioSampleFrame kSampleFlowChunks[] = {")
    for i in range(len(flow)):
        out.append(f"    {{kSampleFlowChunk{i}, sizeof(kSampleFlowChunk{i})}},")
    out.append("};")
    out.append("")
    out.append(f"#define CASIO_SAMPLE_FLOW_COUNT {len(flow)}u")
    out.append("")
    out.append(f"#define CASIO_SAMPLE_FLOW_BYTES {PAIR_BYTES}u")
    out.append("")

    for i, hexstr in enumerate(names):
        out.extend(array(f"kSampleName{i}", hexstr, "0x0018 watch name"))
        out.append("")
    out.append("static const CasioSampleFrame kSampleNames[] = {")
    for i in range(len(names)):
        out.append(f"    {{kSampleName{i}, sizeof(kSampleName{i})}},")
    out.append("};")
    out.append("")
    out.append(f"#define CASIO_SAMPLE_NAME_COUNT {len(names)}u")
    out.append("")

    for i, hexstr in enumerate(conditions):
        out.extend(array(f"kSampleCondition{i}", hexstr, "0x0018 watch condition"))
        out.append("")
    out.append("static const CasioSampleFrame kSampleConditions[] = {")
    for i in range(len(conditions)):
        out.append(f"    {{kSampleCondition{i}, sizeof(kSampleCondition{i})}},")
    out.append("};")
    out.append("")
    out.append(f"#define CASIO_SAMPLE_CONDITION_COUNT {len(conditions)}u")
    out.append("")

    path = os.path.normpath(args.out)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print(
        f"wrote {path}: {len(flow)} flow chunks "
        f"({sum(len(bytes.fromhex(h)) for h, _ in flow)} wire bytes), "
        f"{len(names)} names, {len(conditions)} conditions"
    )


if __name__ == "__main__":
    main()
