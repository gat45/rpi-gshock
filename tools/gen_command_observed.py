#!/usr/bin/env python3
"""Generate casio/command_observed.h from the real DW-H5600 btsnoop captures.

Every number written to the header comes from parsing the ATT CSV exports.
Nothing is hand-written except the file layout.

Usage:
    python tools/gen_command_observed.py [--src DIR] [--out FILE]
"""
from __future__ import annotations

import argparse
import collections
import csv
import glob
import os
import sys

DEFAULT_SRC = os.path.join(
    os.path.dirname(__file__), "..", "..", "..",
    "gshock", "DW-H5600-EMU", "analysis", "btsnoop",
)

OP_CODES = {"0x52": "WRITE_CMD", "0x12": "WRITE_REQ", "0x1B": "NOTIFY"}


def load(src: str):
    files = sorted(glob.glob(os.path.join(src, "*_att.csv")))
    if not files:
        sys.exit(f"no *_att.csv in {src}")

    req = collections.Counter()       # cmd -> count of central writes
    rsp = collections.Counter()       # cmd -> count of watch notifications
    req_handle = collections.defaultdict(collections.Counter)
    rsp_handle = collections.defaultdict(collections.Counter)
    samples = collections.defaultdict(collections.Counter)
    handles = collections.Counter()

    for path in files:
        with open(path, encoding="utf-8", errors="replace") as fh:
            for row in csv.DictReader(fh):
                op = row.get("opcode", "")
                if op not in ("0x52", "0x12", "0x1B"):
                    continue
                raw = (row.get("valeur") or "").strip()
                if len(raw) < 2:
                    continue
                cmd = int(raw[:2], 16)
                handle = int(row.get("handle") or "0", 16)
                handles[(handle, row.get("dir"))] += 1
                if row["dir"] == "C->H":
                    req[cmd] += 1
                    req_handle[cmd][handle] += 1
                else:
                    rsp[cmd] += 1
                    rsp_handle[cmd][handle] += 1
                    samples[cmd][raw[:80]] += 1

    return files, req, rsp, req_handle, rsp_handle, samples, handles


def emit(files, req, rsp, req_handle, rsp_handle, samples, out_path):
    cmds = sorted(set(req) | set(rsp))
    lines = []
    lines.append("/* GENERATED by tools/gen_command_observed.py - do not edit.")
    lines.append(" * Source: %d btsnoop ATT captures." % len(files))
    for path in files:
        lines.append(" *   %s" % os.path.basename(path))
    lines.append(" */")
    lines.append("#pragma once")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("typedef struct {")
    lines.append("    uint8_t id;")
    lines.append("    uint16_t write_handle;")
    lines.append("    uint16_t notify_handle;")
    lines.append("    uint32_t requests;   /* frames sent by the central */")
    lines.append("    uint32_t responses;  /* notifications from the watch */")
    lines.append("    const char* sample;  /* most frequent response, first 80 hex chars */")
    lines.append("} CasioObservedCommand;")
    lines.append("")
    lines.append("static const CasioObservedCommand kObservedCommands[] = {")
    for cmd in cmds:
        wh = req_handle[cmd].most_common(1)
        nh = rsp_handle[cmd].most_common(1)
        sample = samples[cmd].most_common(1)
        sample_txt = sample[0][0] if sample else ""
        lines.append(
            "    {0x%02X, 0x%04X, 0x%04X, %u, %u, \"%s\"},"
            % (
                cmd,
                wh[0][0] if wh else 0,
                nh[0][0] if nh else 0,
                req[cmd],
                rsp[cmd],
                sample_txt,
            )
        )
    lines.append("};")
    lines.append("")
    lines.append("#define CASIO_OBSERVED_COUNT %du" % len(cmds))
    lines.append("")
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {out_path}: {len(cmds)} commands from {len(files)} captures")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=DEFAULT_SRC)
    ap.add_argument(
        "--out",
        default=os.path.join(os.path.dirname(__file__), "..", "casio", "command_observed.h"),
    )
    args = ap.parse_args()
    files, req, rsp, rh, nh, samples, _ = load(args.src)
    emit(files, req, rsp, rh, nh, samples, os.path.normpath(args.out))


if __name__ == "__main__":
    main()
